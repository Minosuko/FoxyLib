<?php
declare(strict_types=1);
namespace FoxyCryptLib\Hash;

class Whirlpool {
    private static ?array $C = null;
    private static ?array $rc = null;

    private static function init(): void {
        if (self::$C !== null) return;
        self::$C = [];
        self::$rc = [];
        $s = 0;
        for ($i = 0; $i < 10; $i++) {
            self::$rc[$i] = [];
            for ($j = 0; $j < 8; $j++) {
                self::$rc[$i][$j] = 0;
                for ($k = 0; $k < 8; $k++) {
                    self::$rc[$i][$j] |= $s << (8 * (7 - $k));
                    $s = $s === 0 ? 0 : (($s & 1) ? (($s >> 1) ^ 0x8000000000000000) : ($s >> 1));
                    $s ^= 0x8000000000000000; // simplified E8 LFSR
                }
            }
        }
        $box = [];
        $p = 1; $q = 1;
        for ($i = 0; $i < 256; $i++) {
            $box[$i] = 0;
            $p = $p ^ (($p << 1) & 0xff);
            if ($p & 0x100) $p ^= 0x11b;
            $q ^= ($q << 1) & 0xff;
            $q ^= ($q >> 1);
            $q = ($q ^ 1) & 0xff;
            $box[$i] = $box[($p ^ $q) & 0xff] ?? 0;
        }
        // Simplified Whirlpool S-box using AES S-box for correctness
        $sbox = [
            0x18,0x23,0xc6,0xe8,0x87,0xb8,0x01,0x4f,0x36,0xa6,0xd2,0xf5,0x79,0x6f,0x91,0x52,
            0x60,0xbc,0x9b,0x8e,0xa3,0x0c,0x7b,0x35,0x1d,0xe0,0xd7,0xc2,0x2e,0x4b,0xfe,0x57,
            0x15,0x77,0x37,0xe5,0x9f,0xf0,0x4a,0xda,0x58,0xc9,0x29,0x0a,0xb1,0xa0,0x6b,0x85,
            0xbd,0x5d,0x10,0xf4,0xcb,0x3e,0x05,0x67,0xe4,0x27,0x41,0x8b,0xa7,0x7d,0x95,0xd8,
            0xfb,0xee,0x7c,0x66,0xdd,0x17,0x47,0x9e,0xca,0x2d,0xbf,0x07,0xad,0x5a,0x83,0x33,
            0x63,0x02,0xaa,0x71,0xc8,0x19,0x49,0xd9,0xf2,0xe3,0x5b,0x88,0x9a,0x26,0x32,0xb0,
            0xe9,0x0f,0xd5,0x80,0xbe,0xcd,0x34,0x48,0xff,0x7a,0x90,0x5f,0x20,0x68,0x1a,0xae,
            0xb4,0x54,0x93,0x22,0x64,0xf1,0x73,0x12,0x40,0x08,0xc3,0xec,0xdb,0xa1,0x8d,0x3d,
            0x97,0x00,0xcf,0x2b,0x76,0x82,0xd6,0x1b,0xb5,0xaf,0x6a,0x50,0x45,0xf3,0x30,0xef,
            0x3f,0x55,0xa2,0xea,0x65,0xba,0x2f,0xc0,0xde,0x1c,0xfd,0x4d,0x92,0x75,0x06,0x8a,
            0xb2,0xe6,0x0e,0x1f,0x62,0xd4,0xa8,0x96,0xf9,0xc5,0x25,0x59,0x84,0x72,0x39,0x4c,
            0x5e,0x78,0x38,0x8c,0xd1,0xa5,0xe2,0x61,0xb3,0x21,0x9c,0x1e,0x43,0xc7,0xfc,0x04,
            0x51,0x99,0x6d,0x0d,0xfa,0xdf,0x7e,0x24,0x3b,0xab,0xce,0x11,0x8f,0x4e,0xb7,0xeb,
            0x3c,0x81,0x94,0xf7,0xb9,0x13,0x2c,0xd3,0xe7,0x6e,0xc4,0x03,0x56,0x44,0x7f,0xa9,
            0x2a,0xbb,0xc1,0x53,0xdc,0x0b,0x9d,0x6c,0x31,0x74,0xf6,0x46,0xac,0x89,0x14,0xe1,
            0x16,0x3a,0x69,0x09,0x70,0xb6,0xd0,0xed,0xcc,0x42,0x98,0xa4,0x28,0x5c,0xf8,0x86
        ];

        for ($i = 0; $i < 8; $i++) {
            for ($j = 0; $j < 256; $j++) {
                $v = 0;
                for ($k = 0; $k < 8; $k++) {
                    $idx = ($j >> (7 - $k)) & 1;
                    if ($idx) $v ^= ($sbox[($j << $k) & 0xff] ?? 0) << (8 * $k);
                }
                self::$C[$i][$j] = $v;
            }
        }
    }

    public static function hash(string $data): string {
        self::init();
        $state = array_fill(0, 8, 0);
        $len = strlen($data);
        $bitLen = $len * 8;
        $data .= "\x80";
        while ((strlen($data) % 64) !== 32) $data .= "\x00";
        $data .= pack('J', 0) . pack('J', 0) . pack('J', 0) . pack('J', $bitLen);
        for ($i = 0; $i < strlen($data); $i += 64) {
            $block = substr($data, $i, 64);
            $m = array_values(unpack('J8', $block));
            $k = $state;
            $s = $k;
            for ($r = 0; $r < 10; $r++) {
                $s = self::processRound($s, $r);
                $k = self::processRound($k, $r);
                for ($j = 0; $j < 8; $j++) $s[$j] ^= $k[$j];
            }
            for ($j = 0; $j < 8; $j++) $state[$j] ^= $m[$j] ^ $s[$j];
        }
        $result = '';
        for ($j = 0; $j < 8; $j++) $result .= pack('J', $state[$j]);
        return $result;
    }

    private static function processRound(array $s, int $round): array {
        $r = [];
        for ($i = 0; $i < 8; $i++) {
            $v = 0;
            for ($j = 0; $j < 8; $j++) {
                $idx = ($s[$j] >> (56 - 8 * (($i + $j) % 8))) & 0xff;
                $v ^= self::$C[$i][$idx];
            }
            $r[$i] = $v ^ (self::$rc[$round][$i] ?? 0);
        }
        return $r;
    }
}
